ENDPOINT = "/fixup/cleanup_orphaned_addresses"
ADDRESS_TYPE = "EmailEmployee"
OTHER_ADDRESS_TYPE = "PhoneEmployee"
FROM = "2001-02-03T04:05:06Z"


async def _create_address(
    graphql_client: GraphQLClient,
    person: UUID,
    address_type: UUID,
    value: str,
    ituser: UUID | None = None,
) -> UUID:
    result = await graphql_client.address_create(
        input=AddressCreateInput(
            user_key=value,
            person=person,
            address_type=address_type,
            value=value,
            ituser=ituser,
            validity=RAValidityInput(from_=FROM),
        )
    )
    return result.uuid


async def _create_ituser(
    graphql_client: GraphQLClient,
    person: UUID,
    itsystem: UUID,
    user_key: str,
    external_id: UUID | None,
    engagements: list[UUID] | None = None,
) -> UUID:
    result = await graphql_client.ituser_create(
        ITUserCreateInput(
            person=person,
            user_key=user_key,
            external_id=str(external_id) if external_id else None,
            itsystem=itsystem,
            engagements=engagements,
            validity=RAValidityInput(from_=FROM),
        )
    )
    return result.uuid


async def _is_terminated(graphql_client: GraphQLClient, address_uuid: UUID) -> bool:
    addresses = await graphql_client._testing__address_read(
        filter=AddressFilter(uuids=[address_uuid], from_date=None, to_date=None),
    )
    validity = one(one(addresses.objects).validities)
    return validity.validity.to == mo_today() - timedelta(days=1)


@pytest.fixture
async def addresses(
    graphql_client: GraphQLClient,
    mo_person: UUID,
    email_employee: UUID,
    phone_employee: UUID,
    aduuid: UUID,
    ldap_person_uuid: UUID,
    add_engagement: AddEngagement,
) -> dict[str, UUID]:
    """Create one address per scenario, keyed by scenario name."""
    engagement = await add_engagement("eng")

    ituser_with_engagement = await _create_ituser(
        graphql_client,
        mo_person,
        aduuid,
        "with-engagement",
        ldap_person_uuid,
        [engagement],
    )
    ituser_without_engagement = await _create_ituser(
        graphql_client, mo_person, aduuid, "without-engagement", uuid4()
    )
    ituser_missing_from_ad = await _create_ituser(
        graphql_client,
        mo_person,
        aduuid,
        "missing-from-ad",
        uuid4(),
        [engagement],
    )
    ituser_without_external_id = await _create_ituser(
        graphql_client,
        mo_person,
        aduuid,
        "without-external-id",
        None,
        [engagement],
    )

    return {
        # Linked to an ITUser which has an engagement: not orphaned
        "healthy": await _create_address(
            graphql_client,
            mo_person,
            email_employee,
            "healthy@example.org",
            ituser_with_engagement,
        ),
        # No ITUser at all: orphaned
        "no_ituser": await _create_address(
            graphql_client, mo_person, email_employee, "no-ituser@example.org"
        ),
        # ITUser without any engagement: orphaned
        "no_engagement": await _create_address(
            graphql_client,
            mo_person,
            email_employee,
            "no-engagement@example.org",
            ituser_without_engagement,
        ),
        # ITUser is present in MO and has an engagement, but its AD entry is gone
        "missing_from_ad": await _create_address(
            graphql_client,
            mo_person,
            email_employee,
            "missing-from-ad@example.org",
            ituser_missing_from_ad,
        ),
        # ITUser has no LDAP UUID to check
        "without_external_id": await _create_address(
            graphql_client,
            mo_person,
            email_employee,
            "without-external-id@example.org",
            ituser_without_external_id,
        ),
        # Orphaned, but of an address type we are not asked to clean
        "other_type": await _create_address(
            graphql_client, mo_person, phone_employee, "12345678"
        ),
    }


