@pytest.mark.usefixtures("healthy", "other_type")
@pytest.mark.parametrize("dry_run_param", [{}, {"dry_run": True}])
async def test_dry_run_reports_without_terminating(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    no_ituser: UUID,
    missing_from_ad: UUID,
    without_external_id: UUID,
    other_itsystem: UUID,
    dry_run_param: dict[str, bool],
) -> None:
    orphaned = [no_ituser, missing_from_ad, without_external_id, other_itsystem]

    response = await test_client.post(
        ENDPOINT, params={"address_type_user_keys": [ADDRESS_TYPE], **dry_run_param}
    )
    assert response.status_code == 200, response.text
    assert set(response.json()) == set(map(str, orphaned))

    for address_uuid in orphaned:
        assert not await _is_terminated(graphql_client, address_uuid)


async def test_terminates_orphaned_addresses(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    healthy: UUID,
    no_ituser: UUID,
    missing_from_ad: UUID,
    without_external_id: UUID,
    other_itsystem: UUID,
    other_type: UUID,
) -> None:
    orphaned = [no_ituser, missing_from_ad, without_external_id, other_itsystem]

    response = await test_client.post(
        ENDPOINT,
        params={"address_type_user_keys": [ADDRESS_TYPE], "dry_run": False},
    )
    assert response.status_code == 200, response.text
    assert set(response.json()) == set(map(str, orphaned))

    for address_uuid in orphaned:
        assert await _is_terminated(graphql_client, address_uuid)
    assert not await _is_terminated(graphql_client, healthy)
    assert not await _is_terminated(graphql_client, other_type)

    # Terminated yesterday, so the addresses are no longer current
    response = await test_client.post(
        ENDPOINT, params={"address_type_user_keys": [ADDRESS_TYPE]}
    )
    assert response.status_code == 200, response.text
    assert response.json() == []


