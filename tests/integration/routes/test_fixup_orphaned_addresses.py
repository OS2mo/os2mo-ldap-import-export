@pytest.mark.usefixtures("healthy", "other_itsystem", "other_type")
async def test_itsystem_user_key_limits_scope(
    test_client: AsyncClient,
    no_ituser: UUID,
    missing_from_ad: UUID,
    without_external_id: UUID,
) -> None:
    response = await test_client.post(
        ENDPOINT,
        params={
            "address_type_user_keys": [ADDRESS_TYPE],
            "itsystem_user_key": "ADUUID",
        },
    )
    assert response.status_code == 200, response.text
    # Unlinked addresses are always eligible; linked ones are scoped to the IT system
    assert set(response.json()) == set(
        map(str, [no_ituser, missing_from_ad, without_external_id])
    )
