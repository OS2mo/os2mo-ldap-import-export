@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_LDAP": "False",
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "LDAP_IT_SYSTEM": "",
    }
)
@pytest.mark.parametrize("num_itusers", (0, 1, 5))
async def test_delete_all_itusers_for_itsystems(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    mo_person: UUID,
    aduuid: UUID,
    num_itusers: int,
) -> None:
    # Populate the (deprecated) IT-system with a number of IT-users
    ituser_uuids = set()
    for _ in range(num_itusers):
        ituser = await graphql_client.ituser_create(
            ITUserCreateInput(
                person=mo_person,
                user_key=str(uuid4()),
                itsystem=aduuid,
                validity=RAValidityInput(from_="1970-01-01T00:00:00"),
            )
        )
        ituser_uuids.add(str(ituser.uuid))

    # Dry-run: expect to see all the IT-user UUIDs that would be deleted
    response = await test_client.post(
        "/fixup/delete_all_itusers_for_itsystems",
        params={"itsystem_user_key": "ADUUID"},
    )
    assert response.status_code == 200
    assert set(response.json()) == ituser_uuids

    # dry_run=False: actually delete them, expecting all the IT-user UUIDs back
    response = await test_client.post(
        "/fixup/delete_all_itusers_for_itsystems",
        params={"itsystem_user_key": "ADUUID", "dry_run": "false"},
    )
    assert response.status_code == 200
    assert set(response.json()) == ituser_uuids

    # The IT-system itself is now gone too, so a follow-up call 404s
    response = await test_client.post(
        "/fixup/delete_all_itusers_for_itsystems",
        params={"itsystem_user_key": "ADUUID"},
    )
    assert response.status_code == 404


