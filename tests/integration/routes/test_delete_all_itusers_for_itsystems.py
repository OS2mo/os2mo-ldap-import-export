@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_LDAP": "False",
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "LDAP_IT_SYSTEM": "",
    }
)
async def test_delete_all_itusers_for_itsystems_aborts_on_dangling(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    mo_person: UUID,
    email_employee: UUID,
    public: UUID,
    aduuid: UUID,
) -> None:
    # Create an IT-user in the (deprecated) IT-system with an address scoped to it
    ituser = await graphql_client.ituser_create(
        ITUserCreateInput(
            person=mo_person,
            user_key=str(uuid4()),
            itsystem=aduuid,
            validity=RAValidityInput(from_="1970-01-01T00:00:00"),
        )
    )
    address = await graphql_client.address_create(
        input=AddressCreateInput(
            value="test@example.com",
            address_type=email_employee,
            visibility=public,
            person=mo_person,
            ituser=ituser.uuid,
            validity=RAValidityInput(from_="1970-01-01T00:00:00"),
        )
    )
    address_uuid = address.uuid

    # A dry-run reports the dangling address via a 409
    response = await test_client.post(
        "/fixup/delete_all_itusers_for_itsystems",
        params={"itsystem_user_key": "ADUUID"},
    )
    assert response.status_code == 409
    detail = response.json()["detail"]
    assert detail["dangling_references"]["addresses"] == [str(address_uuid)]

    # An actual deletion is likewise refused due to the dangling address
    response = await test_client.post(
        "/fixup/delete_all_itusers_for_itsystems",
        params={"itsystem_user_key": "ADUUID", "dry_run": "false"},
    )
    assert response.status_code == 409
    detail = response.json()["detail"]
    assert detail["dangling_references"]["addresses"] == [str(address_uuid)]


