import json
from uuid import UUID

import pytest
from httpx import AsyncClient

from mo_ldap_import_export.autogenerated_graphql_client import GraphQLClient
from mo_ldap_import_export.autogenerated_graphql_client.input_types import (
    EmployeeCreateInput,
)
from mo_ldap_import_export.autogenerated_graphql_client.input_types import (
    ITUserCreateInput,
)


@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "CONVERSION_MAPPING": json.dumps(
            {
                "mo_to_ldap": {
                    "person": {
                        "routing_key": "person",
                        "object_class": "inetOrgPerson",
                        "template": """
                            {{
                                {
                                    "dn": "cn=" ~ uuid ~ ",dc=magenta,dc=dk",
                                    "create": True,
                                    "attributes": {}
                                }|tojson
                            }}
                        """,
                    },
                    "ituser": {
                        "routing_key": "ituser",
                        "object_class": "inetOrgPerson",
                        "template": "{{ skip_if_none(None) }}",
                    },
                }
            }
        ),
    }
)
async def test_inspect_mo_to_ldap_all(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    mo_person: UUID,
    adtitle: UUID,
) -> None:
    person = await graphql_client.person_create(
        input=EmployeeCreateInput(given_name="Other", surname="Person")
    )
    ituser = await graphql_client.ituser_create(
        input=ITUserCreateInput(
            person=mo_person,
            itsystem=adtitle,
            user_key="abk",
            validity={"from": "2020-01-01T00:00:00"},
        )
    )
    first, second = sorted([mo_person, person.uuid])

    response = await test_client.get("/Inspect/mo_to_ldap/person/all")
    assert response.status_code == 200
    with open("/tmp/mo_to_ldap_person.jsonl") as fin:
        rows = [json.loads(line) for line in fin]
    assert rows == [
        {
            "uuid": str(uuid),
            "detail": {
                "message": "Would have created",
                "dn": f"cn={uuid},dc=magenta,dc=dk",
                "object_class": "inetOrgPerson",
                "attributes": {},
            },
        }
        for uuid in [first, second]
    ]

    response = await test_client.get(
        "/Inspect/mo_to_ldap/person/all", params={"start_at": str(first)}
    )
    assert response.status_code == 200
    with open("/tmp/mo_to_ldap_person.jsonl") as fin:
        rows = [json.loads(line) for line in fin]
    assert [row["uuid"] for row in rows] == [str(second)]

    response = await test_client.get("/Inspect/mo_to_ldap/ituser/all")
    assert response.status_code == 200
    with open("/tmp/mo_to_ldap_ituser.jsonl") as fin:
        rows = [json.loads(line) for line in fin]
    assert rows == [
        {"uuid": str(ituser.uuid), "message": "Skipping object as requested"}
    ]


@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "CONVERSION_MAPPING": json.dumps(
            {
                "mo_to_ldap": {
                    "address": {
                        "routing_key": "address",
                        "object_class": "inetOrgPerson",
                        "template": "",
                    }
                }
            }
        ),
    }
)
@pytest.mark.parametrize(
    "identifier,detail",
    [
        ("unknown", "Unknown identifier: unknown"),
        ("address", "Unsupported routing key: address"),
    ],
)
async def test_inspect_mo_to_ldap_all_not_found(
    test_client: AsyncClient, identifier: str, detail: str
) -> None:
    response = await test_client.get(f"/Inspect/mo_to_ldap/{identifier}/all")
    assert response.status_code == 404
    assert response.json() == {"detail": detail}
