DeclareListener: TypeAlias = Callable[[str], Awaitable[UUID]]
EmittedUUIDs: TypeAlias = Callable[[UUID], Awaitable[set[LDAPUUID]]]
EmitSubtree: TypeAlias = Callable[..., Awaitable[set[LDAPUUID]]]


@pytest.fixture
async def declare_listener(graphql_client: GraphQLClient) -> DeclareListener:
    async def inner(user_key: str) -> UUID:
        listener = await graphql_client.declare_event_listener(
            input=ListenerCreateInput(
                namespace="ldap",
                routing_key="uuid",
                user_key=user_key,
            )
        )
        return listener.uuid

    return inner


@pytest.fixture
async def emitted_uuids(graphql_client: GraphQLClient) -> EmittedUUIDs:
    async def inner(listener_uuid: UUID) -> set[LDAPUUID]:
        events = await graphql_client.list_events(listener_uuid)
        return {LDAPUUID(e.subject) for e in events.objects}

    return inner


@pytest.fixture
async def emit_subtree(test_client: AsyncClient) -> EmitSubtree:
    async def inner(search_base: str, **params: str | bool) -> set[LDAPUUID]:
        result = await test_client.request(
            "GET",
            "/ldap_event_generator/since",
            content=search_base,
            headers={"Content-Type": "text/plain"},
            params=params,
        )
        assert result.status_code == 200, result.text
        return {LDAPUUID(u) for u in result.json()}

    return inner


@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "LISTEN_TO_CHANGES_IN_LDAP": "False",
    }
)
async def test_changed_since(emit_subtree: EmitSubtree, ldap_person_uuid: UUID) -> None:
    base = "ou=os2mo,o=magenta,dc=magenta,dc=dk"
    # A `since` predating the person returns it.
    assert await emit_subtree(base, since="2000-01-01T00:00:00Z") == {ldap_person_uuid}
    # A `since` postdating the person excludes it.
    assert await emit_subtree(base, since="2100-01-01T00:00:00Z") == set()


