@pytest.mark.integration_test
@pytest.mark.envvar(
    {"LISTEN_TO_CHANGES_IN_MO": "False", "LISTEN_TO_CHANGES_IN_LDAP": "False"}
)
async def test_changed_since_pagination(
    emit_subtree: EmitSubtree,
    add_ldap_person: AddLdapPerson,
    ldap_api: LDAPAPI,
) -> None:
    uuids = set()
    for x in range(2000):
        ldap_person = await add_ldap_person(str(x), "010170" + str(x).rjust(4, "0"))
        person_dn = combine_dn_strings(ldap_person)
        uuids.add(await ldap_api.get_ldap_unique_ldap_uuid(person_dn))

    returned = await emit_subtree(
        "ou=os2mo,o=magenta,dc=magenta,dc=dk", since="2000-01-01T00:00:00Z"
    )
    assert returned == uuids


@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "LISTEN_TO_CHANGES_IN_LDAP": "False",
    }
)
@pytest.mark.parametrize("dry_run", [True, False])
async def test_emit_subtree(
    declare_listener: DeclareListener,
    emitted_uuids: EmittedUUIDs,
    emit_subtree: EmitSubtree,
    add_ldap_person: AddLdapPerson,
    dnlist2uuid: DNList2UUID,
    ldap_org_unit: list[str],
    dry_run: bool,
) -> None:
    """The UUIDs are always returned; events are emitted only when not dry-running."""
    listener_uuid = await declare_listener("test_emit_subtree")

    person1 = await add_ldap_person("alice", "0101011234")
    person2 = await add_ldap_person("bob", "0202022345")
    expected = {await dnlist2uuid(person1), await dnlist2uuid(person2)}

    returned = await emit_subtree(combine_dn_strings(ldap_org_unit), dry_run=dry_run)
    assert returned == expected

    emitted = await emitted_uuids(listener_uuid)
    assert emitted == (set() if dry_run else expected)


@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "LISTEN_TO_CHANGES_IN_LDAP": "False",
    }
)
async def test_emit_is_subtree_scoped(
    declare_listener: DeclareListener,
    emitted_uuids: EmittedUUIDs,
    emit_subtree: EmitSubtree,
    write_ldap_api: LDAPAPI,
    add_ldap_person: AddLdapPerson,
    dnlist2uuid: DNList2UUID,
    ldap_org: list[str],
    ldap_org_unit: list[str],
) -> None:
    """Only objects at or below the given DN are queued; siblings are excluded."""
    listener_uuid = await declare_listener("test_emit_scoped")

    # Inside the targeted subtree (ou=os2mo).
    inside = await add_ldap_person("dave", "0404044567")
    inside_uuid = await dnlist2uuid(inside)

    # A sibling subtree (ou=other) that must NOT be queued.
    other_ou = ["ou=other"] + ldap_org
    await write_ldap_api.ldap_connection.ldap_add(
        combine_dn_strings(other_ou),
        object_class=["top", "organizationalUnit"],
        attributes={"objectClass": ["top", "organizationalUnit"], "ou": "other"},
    )
    outside = ["uid=erin"] + other_ou
    await write_ldap_api.ldap_connection.ldap_add(
        combine_dn_strings(outside),
        object_class=["top", "person", "organizationalPerson", "inetOrgPerson"],
        attributes={
            "objectClass": ["top", "person", "organizationalPerson", "inetOrgPerson"],
            "uid": "erin",
            "cn": "cn",
            "givenName": "givenName",
            "sn": "sn",
            "employeeNumber": "0505055678",
        },
    )

    returned = await emit_subtree(combine_dn_strings(ldap_org_unit), dry_run=False)
    assert returned == {inside_uuid}

    assert await emitted_uuids(listener_uuid) == {inside_uuid}
