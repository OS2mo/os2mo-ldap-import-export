from typing import Any
from uuid import UUID

import pytest
from more_itertools import only
from pydantic import parse_obj_as

from mo_ldap_import_export.autogenerated_graphql_client.client import GraphQLClient
from mo_ldap_import_export.autogenerated_graphql_client.input_types import (
    OrganisationUnitCreateInput,
)
from mo_ldap_import_export.environments.main import get_org_unit_uuid
from mo_ldap_import_export.environments.main import get_org_unit_uuids


@pytest.mark.integration_test
@pytest.mark.usefixtures("test_client")
@pytest.mark.parametrize(
    "filter,expected",
    [
        # No matches
        ({"user_keys": ["missing"]}, set()),
        # Single match
        ({"user_keys": ["unit1"]}, {"unit1"}),
        ({"user_keys": ["unit1", "missing"]}, {"unit1"}),
        # Multiple matches
        ({"user_keys": ["unit1", "unit2"]}, {"unit1", "unit2"}),
        ({"user_keys": ["unit1", "unit2", "unit3"]}, {"unit1", "unit2", "unit3"}),
    ],
)
async def test_integration_get_org_unit_uuids(
    graphql_client: GraphQLClient,
    afdeling: UUID,
    filter: dict[str, Any],
    expected: set[str],
) -> None:
    async def create_org_unit(user_key: str) -> UUID:
        result = await graphql_client.org_unit_create(
            parse_obj_as(
                OrganisationUnitCreateInput,
                {
                    "name": user_key,
                    "user_key": user_key,
                    "org_unit_type": afdeling,
                    "validity": {"from": "1970-01-01T00:00:00Z"},
                },
            )
        )
        return result.uuid

    units = {
        user_key: await create_org_unit(user_key)
        for user_key in ["unit1", "unit2", "unit3"]
    }
    expected_uuids = {units[user_key] for user_key in expected}

    assert await get_org_unit_uuids(graphql_client, filter) == expected_uuids

    if len(expected_uuids) > 1:
        with pytest.raises(ValueError) as exc_info:
            await get_org_unit_uuid(graphql_client, filter)
        assert "Expected exactly one item in iterable, but got" in str(exc_info.value)
    else:
        assert await get_org_unit_uuid(graphql_client, filter) == only(expected_uuids)
