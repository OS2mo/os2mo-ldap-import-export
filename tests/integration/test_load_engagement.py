@pytest.mark.integration_test
@pytest.mark.usefixtures("test_client")
async def test_load_engagement(
    mo_api: MOAPI,
    graphql_client: GraphQLClient,
    mo_person: UUID,
    mo_org_unit: UUID,
    ansat: UUID,
    jurist: UUID,
    primary: UUID,
) -> None:
    engagement = await graphql_client.engagement_create(
        input=EngagementCreateInput(
            user_key="foo",
            org_unit=mo_org_unit,
            person=mo_person,
            job_function=jurist,
            engagement_type=ansat,
            primary=primary,
            extension_1="one",
            extension_2="two",
            extension_3="three",
            extension_4="four",
            extension_5="five",
            extension_6="six",
            extension_7="seven",
            extension_8="otte",
            extension_9="nine",
            extension_10="ten",
            validity=RAValidityInput(
                from_=datetime(2020, 1, 1),
                to=datetime(2030, 1, 1),
            ),
        )
    )

    result = await load_engagement(mo_api, engagement.uuid)
    assert result is not None
    assert result == Engagement(
        uuid=engagement.uuid,
        user_key="foo",
        org_unit=mo_org_unit,
        person=mo_person,
        job_function=jurist,
        engagement_type=ansat,
        primary=primary,
        extension_1="one",
        extension_2="two",
        extension_3="three",
        extension_4="four",
        extension_5="five",
        extension_6="six",
        extension_7="seven",
        extension_8="otte",
        extension_9="nine",
        extension_10="ten",
        validity=Validity(
            start=datetime(2020, 1, 1, tzinfo=MO_TZ),
            end=datetime(2030, 1, 1, tzinfo=MO_TZ),
        ),
    )


