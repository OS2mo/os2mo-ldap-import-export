"""Integration tests for MOAPI.load_mo_class."""

from uuid import UUID

import pytest
from more_itertools import one

from mo_ldap_import_export.autogenerated_graphql_client import GraphQLClient
from mo_ldap_import_export.autogenerated_graphql_client.input_types import (
    ClassCreateInput,
)
from mo_ldap_import_export.autogenerated_graphql_client.input_types import ValidityInput
from mo_ldap_import_export.moapi import MOAPI


@pytest.mark.integration_test
@pytest.mark.usefixtures("test_client")
async def test_load_mo_class_without_start_date(
    graphql_client: GraphQLClient,
    mo_api: MOAPI,
    role_facet: UUID,
) -> None:
    result = await graphql_client.class_create(
        input=ClassCreateInput(
            user_key="open_start",
            name="Open start",
            facet_uuid=role_facet,
            scope="TEXT",
            validity=ValidityInput(from_=None),
        )
    )
    class_uuid = result.uuid

    classes = await graphql_client.read_classes([class_uuid])
    obj = one(classes.objects)
    validity = one(obj.validities).validity
    assert validity.from_ is None
    assert validity.to is None

    # load_mo_class asserts that `from` is set, and thus crashes on None
    with pytest.raises(AssertionError):
        await mo_api.load_mo_class(class_uuid)
