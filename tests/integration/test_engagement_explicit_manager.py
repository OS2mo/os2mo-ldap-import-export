from tests.integration.conftest import CreateManager as ConftestCreateManager

CreateManager: TypeAlias = Callable[[UUID, str], Awaitable[UUID]]


@pytest.fixture
async def create_manager(
    create_manager: ConftestCreateManager, mo_org_unit: UUID
) -> CreateManager:
    async def inner(person: UUID, user_key: str) -> UUID:
        return await create_manager(
            {
                "user_key": user_key,
                "org_unit": mo_org_unit,
                "responsibility": [],
                "manager_level": uuid4(),
                "manager_type": uuid4(),
                "person": person,
                "validity": RAValidityInput(from_=datetime(2000, 1, 1)),
            }
        )

    return inner


@pytest.mark.integration_test
@pytest.mark.usefixtures("test_client")
@pytest.mark.parametrize("initial", (False, True))
@pytest.mark.parametrize("update", ("unset", "none", "other"))
async def test_moapi_engagement_explicit_manager(
    graphql_client: GraphQLClient,
    mo_api: MOAPI,
    mo_person: UUID,
    mo_org_unit: UUID,
    jurist: UUID,
    ansat: UUID,
    create_manager: CreateManager,
    initial: bool,
    update: str,
) -> None:
    manager1 = await create_manager(mo_person, "manager1")
    manager2 = await create_manager(mo_person, "manager2")
    initial_manager = manager1 if initial else None

    engagement = Engagement(
        user_key="user_key",
        person=mo_person,
        org_unit=mo_org_unit,
        job_function=jurist,
        engagement_type=ansat,
        primary=None,
        fraction=None,
        explicit_manager=initial_manager if initial else models.UNSET,
        validity=Validity(start=datetime(2020, 1, 1), end=None),
    )
    engagement_uuid = await mo_api.create_engagement(engagement)
    loaded = await mo_api.load_mo_engagement(engagement_uuid)
    assert loaded is not None
    assert loaded.explicit_manager == initial_manager

    explicit_manager, expected = {
        "unset": (models.UNSET, initial_manager),
        "none": (None, None),
        "other": (manager2, manager2),
    }[update]
    await mo_api.edit_engagement(
        loaded.copy(update={"explicit_manager": explicit_manager})
    )
    loaded = await mo_api.load_mo_engagement(engagement_uuid)
    assert loaded is not None
    assert loaded.explicit_manager == expected


@pytest.mark.integration_test
@pytest.mark.usefixtures("test_client")
async def test_get_manager_uuid(
    graphql_client: GraphQLClient,
    mo_person: UUID,
    create_manager: CreateManager,
) -> None:
    manager1 = await create_manager(mo_person, "manager1")
    await create_manager(mo_person, "manager2")

    assert await get_manager_uuid(graphql_client, {"user_keys": ["manager1"]}) == (
        manager1
    )
    assert await get_manager_uuid(graphql_client, {"user_keys": ["unknown"]}) is None
    with pytest.raises(ValueError):
        await get_manager_uuid(
            graphql_client, {"employee": {"uuids": [str(mo_person)]}}
        )
