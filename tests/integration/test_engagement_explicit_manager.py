from datetime import datetime
from uuid import UUID
from uuid import uuid4

import pytest

from mo_ldap_import_export.autogenerated_graphql_client import GraphQLClient
from mo_ldap_import_export.autogenerated_graphql_client import RAValidityInput
from mo_ldap_import_export.autogenerated_graphql_client.input_types import (
    ManagerCreateInput,
)
from mo_ldap_import_export.environments.main import load_engagement
from mo_ldap_import_export.moapi import MOAPI
from mo_ldap_import_export.models import UNSET
from mo_ldap_import_export.models import Engagement
from mo_ldap_import_export.models import UnsetType
from mo_ldap_import_export.models import Validity


@pytest.mark.integration_test
@pytest.mark.usefixtures("test_client")
async def test_engagement_explicit_manager(
    graphql_client: GraphQLClient,
    mo_api: MOAPI,
    mo_person: UUID,
    mo_org_unit: UUID,
    ansat: UUID,
    jurist: UUID,
) -> None:
    manager = await graphql_client._testing__manager_create(
        ManagerCreateInput(
            org_unit=mo_org_unit,
            responsibility=[],
            manager_level=uuid4(),
            manager_type=uuid4(),
            validity=RAValidityInput(from_=datetime(2000, 1, 1)),
        )
    )

    async def edit(
        explicit_manager: UUID | None | UnsetType,
    ) -> UUID | None | UnsetType:
        engagement = await load_engagement(mo_api, engagement_uuid)
        assert engagement is not None
        await mo_api.edit_engagement(
            engagement.copy(update={"explicit_manager": explicit_manager})
        )
        engagement = await load_engagement(mo_api, engagement_uuid)
        assert engagement is not None
        return engagement.explicit_manager

    # Create without explicit_manager
    engagement_uuid = await mo_api.create_engagement(
        Engagement(
            user_key="foo",
            org_unit=mo_org_unit,
            person=mo_person,
            job_function=jurist,
            engagement_type=ansat,
            primary=None,
            validity=Validity(start=datetime(2020, 1, 1), end=None),
        )
    )
    assert await edit(UNSET) is None
    # Set
    assert await edit(manager.uuid) == manager.uuid
    # Keep
    assert await edit(UNSET) == manager.uuid
    # Clear
    assert await edit(None) is None
