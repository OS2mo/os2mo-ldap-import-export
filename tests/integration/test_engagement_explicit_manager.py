@pytest.mark.usefixtures("test_client")
async def test_ldap_to_mo_explicit_manager(
    graphql_client: GraphQLClient,
    mo_api: MOAPI,
    ldap_api: LDAPAPI,
    ldap_person_dn: DN,
    add_ldap_person: AddLdapPerson,
    trigger_ldap_person: Callable[[], Awaitable[None]],
    create_manager: CreateManager,
    mo_person: UUID,
    mo_org_unit: UUID,
    ansat: UUID,
    jurist: UUID,
    primary: UUID,
) -> None:
    engagement = await graphql_client.engagement_create(
        input=EngagementCreateInput(
            user_key="engagement",
            person=mo_person,
            org_unit=mo_org_unit,
            engagement_type=ansat,
            job_function=jurist,
            primary=primary,
            validity=RAValidityInput(from_=datetime(2001, 2, 3)),
        )
    )

    async def read_explicit_manager() -> UUID | None:
        loaded = await mo_api.load_mo_engagement(engagement.uuid)
        assert loaded is not None
        assert loaded.explicit_manager != models.UNSET
        return loaded.explicit_manager

    # Two managers, each existing in both MO (with a manager role) and LDAP
    managers = {}
    for uid, cpr_number in [("boss1", "0101700001"), ("boss2", "0101700002")]:
        person = await graphql_client.person_create(
            input=EmployeeCreateInput(
                given_name=uid, surname=uid, cpr_number=cpr_number
            )
        )
        manager_uuid = await create_manager(person.uuid, uid)
        manager_dn = combine_dn_strings(await add_ldap_person(uid, cpr_number))
        managers[manager_dn] = manager_uuid
    (dn1, manager1), (dn2, manager2) = managers.items()

    # No manager attribute in LDAP leaves the engagement untouched
    await trigger_ldap_person()
    assert await read_explicit_manager() is None

    for manager_dn, manager_uuid in [(dn1, manager1), (dn2, manager2)]:
        await ldap_api.ldap_connection.ldap_modify(
            dn=ldap_person_dn,
            changes={"manager": [(MODIFY_REPLACE, [manager_dn])]},
        )
        await trigger_ldap_person()
        assert await read_explicit_manager() == manager_uuid
