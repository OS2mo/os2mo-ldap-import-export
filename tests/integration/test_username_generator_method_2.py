@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "LISTEN_TO_CHANGES_IN_LDAP": "False",
        "CONVERSION_MAPPING": json.dumps(
            {
                "username_generator": {
                    "char_replacement": CHAR_REPLACEMENT,
                    "combinations_to_try": COMBINATIONS,
                }
            }
        ),
    }
)
@pytest.mark.usefixtures("test_client")
async def test_generate_username_method_2_allocation_order(
    graphql_client: GraphQLClient,
    context: Context,
    add_ldap_person: AddLdapPerson,
) -> None:
    """Allocate every username available to Karina Jensen."""
    mo_person = await graphql_client.person_create(
        input=EmployeeCreateInput(
            given_name="Karina", surname="Jensen", cpr_number="0101700000"
        )
    )
    expected_usernames = [
        # 1. priority
        "kjens",
        "kajen",
        "karje",
        "karij",
        "jense",
        # 2. priority
        "kjen",
        "kaje",
        "karj",
        # 3. priority
        "kje",
        "kaj",
        # 4. priority
        *[f"k{x}jen" for x in range(2, 10)],
        *[f"ka{x}je" for x in range(2, 10)],
        *[f"kar{x}j" for x in range(2, 10)],
        *[f"kari{x}" for x in range(2, 10)],
        # 5. priority
        *[f"kaj{x}" for x in range(2, 10)],
        *[f"kar{x}" for x in range(2, 10)],
        *[f"jen{x}" for x in range(2, 10)],
        # Spec omits "ka2j"
        *[f"ka{x}j" for x in range(2, 10)],
        *[f"k{x}je" for x in range(2, 10)],
        # 6. priority
        "kjense",
        "kajens",
        "karjen",
        "karije",
        "karinj",
    ]

    dataloader = context["user_context"]["dataloader"]
    for expected_username in expected_usernames:
        username = await generate_username(dataloader, mo_person.uuid)
        assert username == expected_username
        await add_ldap_person(username, "0101701234")

    with pytest.raises(RuntimeError) as exc_info:
        await generate_username(dataloader, mo_person.uuid)
    assert "Failed to create user name." in str(exc_info.value)
