    names = [
        ["Pia", "Munk", "Jensen"],
        ["Anders", "Kristian", "Jens", "Peter", "Andersen"],
        ["Karina", "Jensen"],
        ["Karina", "Munk", "Jensen"],
        ["Olê", "Østergård", "Høst", "Ærøe"],
    ]
    clean_names = [_name_fixer(CHAR_REPLACEMENT, False, name) for name in names]
    usernames = [
        _create_from_combi(clean_name, combination) for clean_name in clean_names
    ]
    # The specification shows the first number tried for X, which is 2
    numbered_usernames = [
        username.replace("X", "2") if username else None for username in usernames
    ]
    assert numbered_usernames == expected


