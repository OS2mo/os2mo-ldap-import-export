@pytest.mark.integration_test
@pytest.mark.parametrize(
    "initial, update, expected",
    [
        # Created without a title
        (None, None, None),
        (None, UNSET, None),
        (None, "skoleunderviser", "skoleunderviser"),
        (UNSET, None, None),
        (UNSET, UNSET, None),
        (UNSET, "skoleunderviser", "skoleunderviser"),
        # Created with a title, which is only kept when the update is UNSET
        ("skoleunderviser", None, None),
        ("skoleunderviser", UNSET, "skoleunderviser"),
        ("skoleunderviser", "skoleunderviser", "skoleunderviser"),
        ("skoleunderviser", "softwareudvikler", "softwareudvikler"),
    ],
)
@pytest.mark.usefixtures("test_client")
async def test_engagement_title(
    mo_api: MOAPI,
    mo_person: UUID,
    mo_org_unit: UUID,
    ansat: UUID,
    jurist: UUID,
    skoleunderviser: UUID,
    softwareudvikler: UUID,
    initial: str | None | UnsetType,
    update: str | None | UnsetType,
    expected: str | None,
) -> None:
    titles: dict[str | None, UUID | None | UnsetType] = {
        "skoleunderviser": skoleunderviser,
        "softwareudvikler": softwareudvikler,
    }

    engagement_uuid = await mo_api.create_engagement(
        Engagement(
            user_key="foo",
            org_unit=mo_org_unit,
            person=mo_person,
            job_function=jurist,
            engagement_type=ansat,
            primary=None,
            title=titles.get(initial, initial),
            validity=Validity(start=datetime(2020, 1, 1), end=None),
        )
    )

    engagement = await load_engagement(mo_api, engagement_uuid)
    assert engagement is not None
    await mo_api.edit_engagement(
        engagement.copy(update={"title": titles.get(update, update)})
    )

    engagement = await load_engagement(mo_api, engagement_uuid)
    assert engagement is not None
    assert engagement.title == titles.get(expected, expected)


@pytest.mark.integration_test
@pytest.mark.envvar(
    {
        "LISTEN_TO_CHANGES_IN_MO": "False",
        "LISTEN_TO_CHANGES_IN_LDAP": "False",
        "CONVERSION_MAPPING": json.dumps(
            {
                "ldap_to_mo": {
                    "Engagement": {
                        "objectClass": "Engagement",
                        "_import_to_mo_": "true",
                        "_ldap_attributes_": ["title"],
                        # Call load engagement on each of the persons engagements,
                        # exposing the MO engagement objects as each for the mapping.
                        "_for_each_": """
                            {% set engagements = get_engagement_uuids(
                                {"employee": {"uuids": [employee_uuid]}}
                            ) %}
                            [
                                {% for engagement in engagements %}
                                    {{ load_mo_engagement(engagement).json() }}
                                    {% if not loop.last %},{% endif %}
                                {% endfor %}
                            ]
                        """,
                        "uuid": "{{ each.uuid }}",
                        "user_key": "{{ each.user_key }}",
                        "person": "{{ each.person }}",
                        "org_unit": "{{ each.org_unit }}",
                        "engagement_type": "{{ each.engagement_type }}",
                        "job_function": "{{ each.job_function }}",
                        "primary": "{{ each.primary }}",
                        "title": "{{ get_or_create_title_uuid(ldap.title) }}",
                    },
                },
            }
        ),
    }
)
@pytest.mark.usefixtures("test_client", "title_facet")
async def test_to_mo_for_each_only_changes_title(
    graphql_client: GraphQLClient,
    mo_api: MOAPI,
    mo_person: UUID,
    mo_org_unit: UUID,
    ansat: UUID,
    jurist: UUID,
    primary: UUID,
    trigger_ldap_person: Callable[[], Awaitable[None]],
) -> None:
    """Only the title is changed, every other field is carried over by `each`.

    The title class does not exist in MO beforehand, so it is created from the
    value found in LDAP.
    """

    async def get_title_class() -> TitleClass:
        classes = await graphql_client._testing__class_read(
            filter=ClassFilter(facet=FacetFilter(user_keys=["title"]))
        )
        return one(one(classes.objects).validities)

    engagement_uuid = await mo_api.create_engagement(
        Engagement(
            user_key="engagement",
            org_unit=mo_org_unit,
            person=mo_person,
            job_function=jurist,
            engagement_type=ansat,
            primary=primary,
            extension_1="extension",
            validity=Validity(start=datetime(2020, 1, 1), end=None),
        )
    )
    before = await load_engagement(mo_api, engagement_uuid)
    assert before is not None
    assert before.title is None

    # The LDAP title has no class in MO, so the import creates one
    await trigger_ldap_person()

    title = await get_title_class()
    assert title.user_key == "Skole underviser"
    after = await load_engagement(mo_api, engagement_uuid)
    assert after == before.copy(
        update={
            "title": title.uuid,
            # The edit only touches the current validity, which starts today
            "validity": Validity(start=mo_today(), end=before.validity.end),
        }
    )

    # Importing again reuses the class instead of creating a duplicate
    await trigger_ldap_person()

    assert await get_title_class() == title
    assert await load_engagement(mo_api, engagement_uuid) == after
